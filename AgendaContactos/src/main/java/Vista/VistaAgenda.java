    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String nombre = txtNombreGuardar.getText();
        String telefono = txtTelefonoGuardar.getText();

    if (!nombre.isEmpty() && !telefono.isEmpty()) {
        controlador.agregarContacto(nombre, telefono);
        JOptionPane.showMessageDialog(this, "¡Contacto guardado con éxito!");
        txtNombreGuardar.setText("");
        txtTelefonoGuardar.setText("");
    } else {
        JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton1ActionPerformed

