    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    String nombreBuscado = txtNombreBuscar.getText();

        if (!nombreBuscado.isEmpty()) {
          String telefonoEncontrado = controlador.buscarContacto(nombreBuscado);
        if (telefonoEncontrado != null) {
        lblResultado.setText("Teléfono: " + telefonoEncontrado);
        } else {
        lblResultado.setText("Contacto no encontrado.");
         }
        } else {
        JOptionPane.showMessageDialog(this, "Ingrese un nombre para buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
    }    // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

